#include <iostream>
using namespace std;

/*
    Arithmetic operators
    "For Mathematical Operations"

    --- + => Addition
    --- - => Subtraction
    --- * => Multiplication
    --- / => Division
    --- % => Modulo => Remainder After Division
    */

int main(){
    cout<< 10 + 10 << endl; // 20

    cout<< 10 - 7 << endl; // 3

    cout<< 11 * 6 << endl; // 66

    cout<< 100 / 5 << endl; // 20

    cout<< 12 % 2 << endl; // 0


    return 0;
}