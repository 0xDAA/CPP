#include <iostream>
using namespace std;
int main() {
    int a; // Declare Variable Without Value
    a = 504; // Attribution Value 504 in variable a
    cout<< a; // Print a (504)

    cout <<"\n============\n";

    int b,c,d; // Declare Multiple Variables Without Value
    b=15,c=14,d=14;
    cout << b+c+d; // 43

    cout <<"\n============\n";

    int e,f,g;
    e=f=g=100; // All same value (100)
    cout <<e+f+g; // 300

}
