#include<iostream>
#include <vector>
using namespace std;


int main() {
    vector<int> array = {10,20,300,40};
    // array.at() function
    cout<<array.at(0)<<endl;
    cout<<array.at(1)<<endl;
    cout<<array.at(2)<<endl;
    cout<<array.at(3)<<endl;
    // array[] method:
    cout<<array[0]<<endl;
    cout<<array[1]<<endl;
    cout<<array[2]<<endl;
    cout<<array[3]<<endl;

}

